// Every plain declaration gets !important, except in @font-face and on our own ::before blocks (no Firefox
// rule competes there).
function important(css) {
  let block = '';
  return css
    .split('\n')
    .map((line) => {
      if (/\{\s*$/.test(line)) block = line;
      if (/@font-face|::before/.test(block)) return line;
      return /^\s+[a-z-]+:\s.*;$/.test(line) && !line.includes('!important') ? line.replace(/;$/, ' !important;') : line;
    })
    .join('\n');
}

export function userChrome(t) {
  return important(t.kind === 'lcars' ? lcars(t) : phosphor(t));
}

