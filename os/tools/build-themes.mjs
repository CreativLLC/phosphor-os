// Writes the text files of the three OS themes from palettes.mjs:
//   os/omarchy/themes/<id>/  colors.toml shell.toml hyprland.lua btop.theme chromium.theme icons.theme keyboard.rgb
//   os/windows/terminal-schemes.json
//   os/firefox/<id>/userChrome.css userContent.css   (see firefox-css.mjs)
// Run: node os/tools/build-themes.mjs   (images come from wallpapers.mjs)
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { themes, builtinColorKeys } from './palettes.mjs';
import { userChrome, userContent } from './firefox-css.mjs';

const OS = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEAD = (c) => `${c} Phosphor-OS OS theme. Generated by os/tools/build-themes.mjs from palettes.mjs.\n`;

function write(rel, text) {
  const p = join(OS, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, text.replace(/\r\n/g, '\n'));
}

const strip = (hex) => hex.replace('#', '');

function colorsToml(t) {
  const c = t.colors;
  const line = (k) => `${k} = "${c[k]}"`;
  const group = (keys) => keys.map(line).join('\n');
  return (
    HEAD('#') +
    `# Omarchy reads this palette and fills every app template from it (terminals, btop, editors, browser, shell).\n\n` +
    `${line('mode')}\n\n` +
    group(['accent', 'selection', 'muted']) + '\n\n' +
    group(['background', 'dark_background', 'darker_background', 'lighter_background']) + '\n\n' +
    group(['foreground', 'dark_foreground', 'light_foreground', 'bright_foreground']) + '\n\n' +
    group(['selection_background', 'selection_foreground']) + '\n\n' +
    group(['hyprland_active_border', 'hyprland_inactive_border', 'active_border_color', 'active_tab_background']) + '\n\n' +
    group(['red', 'yellow', 'orange', 'green', 'cyan', 'blue', 'magenta', 'brown']) + '\n\n' +
    group(['bright_red', 'bright_yellow', 'bright_green', 'bright_cyan', 'bright_blue', 'bright_magenta']) + '\n'
  );
}

