// Hyprland 0.5x Lua config, loaded by Omarchy after its defaults and before ~/.config/hypr/looknfeel.lua.
function hyprlandLua(t) {
  const c = t.colors;
  const h = t.hypr;
  const isL = t.kind === 'lcars';
  const glow = h.glow
    ? `
    -- Phosphor glow: a soft shadow in the phosphor color, no offset, only on the focused window.
    shadow = {
      enabled = true,
      range = 14,
      render_power = 3,
      color = "${t.tone.glowRgba}",
      color_inactive = "rgba(00000000)",
    },`
    : `
    shadow = {
      enabled = false,
    },`;
  const groupbar = isL
    ? `
    -- Tab groups read as LCARS blocks: black text on solid color bars.
    groupbar = {
      font_weight_active = "bold",
      font_weight_inactive = "bold",
      text_color = "rgb(000000)",
      text_color_inactive = "rgb(000000)",
      gradients = true,
      gradient_rounding = 10,
      gradient_round_only_edges = false,
      col = {
        active = "rgb(${strip(t.lcars.orange)})",
        inactive = "rgb(${strip(t.lcars.lavender)})",
      },
    },`
    : `
    groupbar = {
      text_color = "rgb(${strip(c.bright_foreground)})",
      text_color_inactive = "rgb(${strip(c.dark_foreground)})",
      gradient_rounding = 0,
      col = {
        active = "rgba(${strip(c.foreground)}38)",
        inactive = "rgba(${strip(c.foreground)}10)",
      },
    },`;
  return `-- Phosphor-OS OS theme. Generated by os/tools/build-themes.mjs from palettes.mjs.
-- ${isL ? 'LCARS: rounded corners, thick solid borders, flat color.' : 'Phosphor: square corners, thin bright borders, a soft glow on the focused window.'}
-- Your ~/.config/hypr/looknfeel.lua loads after this and wins.

local active_border_color = "${c.hyprland_active_border}"
local inactive_border_color = "${c.hyprland_inactive_border}"

hl.config({
  general = {
    border_size = ${h.border},
    gaps_in = ${h.gapsIn},
    gaps_out = ${h.gapsOut},
    col = {
      active_border = active_border_color,
      inactive_border = inactive_border_color,
    },
  },

  decoration = {
    rounding = ${h.rounding},${isL ? '\n    rounding_power = 2,' : ''}${glow}
  },

  group = {
    col = {
      border_active = active_border_color,
      border_inactive = inactive_border_color,
    },
${groupbar}
  },
})
`;
}

// btop: the template's rainbow gradients become phosphor ramps (dim to bright) or LCARS block colors.
function btopTheme(t) {
  const c = t.colors;
  const isL = t.kind === 'lcars';
  const L = t.lcars || {};
  const ramp = (a, b, d) => ({ start: a, mid: b, end: d });
  const ph = ramp(c.dark_foreground, c.foreground, c.bright_foreground);
  const g = isL
    ? {
        title: L.orange, hi: L.gold, selBg: c.selection, selFg: L.gold, inactive: c.muted, graphText: c.light_foreground,
        meterBg: '#1a1a2e', misc: L.lilac, cpuBox: L.orange, memBox: L.lilac, netBox: L.periwinkle, procBox: L.gold, div: '#333355',
        temp: ramp(L.periwinkle, L.gold, L.red), cpu: ramp(L.periwinkle, L.lilac, L.orange), free: ramp(L.lavender, L.periwinkle, '#99ccff'),
        cached: ramp(L.lilac, L.lavender, L.periwinkle), avail: ramp(L.gold, L.orange, L.orange), used: ramp(L.peach, L.orange, L.red),
        down: ramp(L.lavender, L.periwinkle, '#bbbbff'), up: ramp(L.peach, L.gold, L.orange), proc: ramp(L.lavender, L.lilac, L.orange),
      }
    : {
        title: c.bright_foreground, hi: c.bright_foreground, selBg: c.selection, selFg: c.bright_foreground, inactive: c.muted, graphText: c.light_foreground,
        meterBg: c.lighter_background, misc: c.foreground, cpuBox: c.dark_foreground, memBox: c.dark_foreground, netBox: c.dark_foreground, procBox: c.dark_foreground, div: c.muted,
        temp: ramp(c.dark_foreground, c.foreground, c.red), cpu: ph, free: ph, cached: ph, avail: ph, used: ph, down: ph, up: ph, proc: ph,
      };
  const q = (k, v) => `theme[${k}]="${v}"`;
  const r = (name, x) => [q(`${name}_start`, x.start), q(`${name}_mid`, x.mid), q(`${name}_end`, x.end)].join('\n');
  const grad = isL
    ? [c.background, '#121220', '#33335c', L.lavender, L.lilac, L.peach, L.gold, L.orange]
    : [c.background, c.lighter_background, c.selection, c.muted, c.dark_foreground, c.foreground, c.light_foreground, c.bright_foreground];
  return `${HEAD('#')}
# Main background, empty for terminal default
${q('main_bg', c.background)}
${q('main_fg', c.foreground)}
${q('title', g.title)}
${q('hi_fg', g.hi)}
${q('selected_bg', g.selBg)}
${q('selected_fg', g.selFg)}
${q('inactive_fg', g.inactive)}
${q('graph_text', g.graphText)}
${q('meter_bg', g.meterBg)}
${q('proc_misc', g.misc)}

# Box outlines and dividers
${q('cpu_box', g.cpuBox)}
${q('mem_box', g.memBox)}
${q('net_box', g.netBox)}
${q('proc_box', g.procBox)}
${q('div_line', g.div)}

# Meters and graphs
${r('temp', g.temp)}
${r('cpu', g.cpu)}
${r('free', g.free)}
${r('cached', g.cached)}
${r('available', g.avail)}
${r('used', g.used)}
${r('download', g.down)}
${r('upload', g.up)}
${r('process', g.proc)}

# Graph shades, background to brightest
${grad.map((v, i) => q(`gradient_color_${i}`, v)).join('\n')}
`;
}

// Windows Terminal: a settings "fragment" ({ "schemes": [...] }) that also works for copy and paste.
function terminalSchemes() {
  const schemes = Object.values(themes).map((t) => {
    const c = t.colors;
    return {
      name: `Phosphor-OS ${t.title.replace('Retro ', '')}`,
      background: c.background.toUpperCase(),
      foreground: c.foreground.toUpperCase(),
      cursorColor: c.bright_foreground.toUpperCase(),
      selectionBackground: c.selection.toUpperCase(),
      black: c.background.toUpperCase(),
      red: c.red.toUpperCase(),
      green: c.green.toUpperCase(),
      yellow: c.yellow.toUpperCase(),
      blue: c.blue.toUpperCase(),
      purple: c.magenta.toUpperCase(),
      cyan: c.cyan.toUpperCase(),
      white: c.foreground.toUpperCase(),
      brightBlack: c.muted.toUpperCase(),
      brightRed: c.bright_red.toUpperCase(),
      brightGreen: c.bright_green.toUpperCase(),
      brightYellow: c.bright_yellow.toUpperCase(),
      brightBlue: c.bright_blue.toUpperCase(),
      brightPurple: c.bright_magenta.toUpperCase(),
      brightCyan: c.bright_cyan.toUpperCase(),
      brightWhite: c.bright_foreground.toUpperCase(),
    };
  });
  return JSON.stringify({ schemes }, null, 2) + '\n';
}

for (const t of Object.values(themes)) {
  const missing = builtinColorKeys.filter((k) => !(k in t.colors));
  if (missing.length) throw new Error(`${t.id}: colors.toml is missing ${missing.join(', ')}`);
  const dir = `omarchy/themes/${t.id}`;
  write(`${dir}/colors.toml`, colorsToml(t));
  write(`${dir}/shell.toml`, shellToml(t));
  write(`${dir}/hyprland.lua`, hyprlandLua(t));
  write(`${dir}/btop.theme`, btopTheme(t));
  write(`${dir}/chromium.theme`, t.chromium + '\n');
  write(`${dir}/icons.theme`, t.icons + '\n');
  write(`${dir}/keyboard.rgb`, strip(t.colors.accent) + '\n');
  write(`firefox/${t.id}/userChrome.css`, userChrome(t));
  write(`firefox/${t.id}/userContent.css`, userContent(t));
}
write('windows/terminal-schemes.json', terminalSchemes());
console.log('themes written:', Object.keys(themes).join(', '));
